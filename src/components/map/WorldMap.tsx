"use client";

import { useEffect, useMemo, useRef } from "react";
import {
  AttributionControl,
  Map as MapLibreMap,
  NavigationControl,
  Popup,
  setWorkerUrl,
} from "maplibre-gl";
import type {
  AddLayerObject,
  GeoJSONSource,
  LngLatLike,
  StyleSpecification,
} from "maplibre-gl";
import type { FeatureCollection, Point } from "geojson";
import "maplibre-gl/dist/maplibre-gl.css";
import type { Event } from "@/lib/types";
import type { Vessel, VesselBox } from "@/lib/vessels/types";
import { CHOKEPOINTS, watchAreaCollection } from "@/lib/vessels/maritime";

// Turbopack does not rewrite MapLibre's bundler-generated worker URL, so the
// worker is served as a static file instead (generated by
// scripts/copy-maplibre-worker.mjs before dev/build).
setWorkerUrl("/maplibre-gl-worker.mjs");

// ---------------------------------------------------------------------------
// World map — MapLibre GL with OpenFreeMap vector basemaps.
//
// Honesty rules:
//   - only events with real coordinates are plotted
//   - country/region-level events are drawn as large translucent areas,
//     never as precise pins
//   - the map is lazy-loaded and entirely optional: if it fails, every other
//     view of ORBIS still works
//
// Basemap: OpenFreeMap vector styles (free, keyless). A raster tile provider
// can be substituted with ORBIS_TILE_URL, and then only raster tiles are used.
// ---------------------------------------------------------------------------

const OPENFREEMAP_ATTRIBUTION =
  "© OpenFreeMap contributors · © OpenStreetMap contributors";

const STYLE_URLS: Record<"light" | "dark", string> = {
  light: "https://tiles.openfreemap.org/styles/positron",
  dark: "https://tiles.openfreemap.org/styles/dark",
};

const PRECISION_STYLE: Record<string, { radius: number; opacity: number }> = {
  exact: { radius: 6, opacity: 0.9 },
  city: { radius: 7, opacity: 0.75 },
  admin: { radius: 10, opacity: 0.4 },
  country: { radius: 14, opacity: 0.18 },
  region: { radius: 18, opacity: 0.14 },
  uncertain: { radius: 20, opacity: 0.12 },
};

const CRITICAL_COLOR = "#b91c1c";
const NOTABLE_COLOR = "#b45309";
const ROUTINE_COLOR = "#059669";

const EVENT_SOURCE = "orbis-events";
const EVENT_LAYER = "orbis-events-circle";
const VESSEL_SOURCE = "orbis-vessels";
const VESSEL_LAYER = "orbis-vessels-circle";
const VESSEL_COLOR = "#0e7490";
/** Badge colors: listed hulls (operator's own reference list) stand out
 * from heuristic "possible" matches — both distinct from ordinary vessels. */
const NAVAL_LISTED_COLOR = "#7c3aed";
const NAVAL_POSSIBLE_COLOR = "#c2410c";
const WATCH_SOURCE = "orbis-watch-area";
const WATCH_LAYER = "orbis-watch-area-line";
const CHOKE_SOURCE = "orbis-chokepoints";
const CHOKE_LAYER = "orbis-chokepoints-circle";
const CHOKE_COLOR = "#d97706";

function rasterStyle(tileUrl: string, tileAttribution?: string): StyleSpecification {
  return {
    version: 8,
    sources: {
      base: {
        type: "raster",
        tiles: [tileUrl],
        tileSize: 256,
        attribution: tileAttribution ?? "© OpenStreetMap contributors",
      },
    },
    layers: [{ id: "base", type: "raster", source: "base" }],
  };
}

function buildEventLayer(): AddLayerObject {
  return {
    id: EVENT_LAYER,
    type: "circle" as const,
    source: EVENT_SOURCE,
    paint: {
      "circle-color": [
        "match",
        ["get", "level"],
        "critical",
        CRITICAL_COLOR,
        "notable",
        NOTABLE_COLOR,
        "routine",
        ROUTINE_COLOR,
        ROUTINE_COLOR,
      ],
      "circle-stroke-color": [
        "match",
        ["get", "level"],
        "critical",
        CRITICAL_COLOR,
        "notable",
        NOTABLE_COLOR,
        "routine",
        ROUTINE_COLOR,
        ROUTINE_COLOR,
      ],
      "circle-radius": ["get", "radius"],
      "circle-opacity": ["get", "opacity"],
      "circle-stroke-opacity": ["get", "strokeOpacity"],
      "circle-stroke-width": 1,
    },
  };
}

function buildVesselLayer(show: boolean): AddLayerObject {
  return {
    id: VESSEL_LAYER,
    type: "circle" as const,
    source: VESSEL_SOURCE,
    layout: { visibility: show ? ("visible" as const) : ("none" as const) },
    paint: {
      "circle-color": [
        "match",
        ["get", "naval"],
        "listed",
        NAVAL_LISTED_COLOR,
        "possible",
        NAVAL_POSSIBLE_COLOR,
        VESSEL_COLOR,
      ],
      "circle-radius": ["match", ["get", "naval"], "listed", 5, "possible", 4.5, 3.5],
      "circle-opacity": 0.85,
      "circle-stroke-color": "#ffffff",
      "circle-stroke-width": 0.5,
      "circle-stroke-opacity": 0.8,
    },
  };
}

/** Dashed outline of the configured AIS watch area (reference only). */
function buildWatchLayer(): AddLayerObject {
  return {
    id: WATCH_LAYER,
    type: "line" as const,
    source: WATCH_SOURCE,
    paint: {
      "line-color": VESSEL_COLOR,
      "line-width": 1.5,
      "line-dasharray": [3, 2],
      "line-opacity": 0.7,
    },
  };
}

/** Major straits/canals — static reference marks, always visible. */
function buildChokeLayer(): AddLayerObject {
  return {
    id: CHOKE_LAYER,
    type: "circle" as const,
    source: CHOKE_SOURCE,
    paint: {
      "circle-color": CHOKE_COLOR,
      "circle-radius": 5,
      "circle-opacity": 0.9,
      "circle-stroke-color": "#ffffff",
      "circle-stroke-width": 1.2,
    },
  };
}

interface Props {
  events: Event[];
  onSelect: (event: Event) => void;
  /** Current AIS positions (context only). Hidden unless `showVessels`. */
  vessels?: Vessel[];
  showVessels?: boolean;
  onVesselSelect?: (mmsi: string) => void;
  /** Configured AIS watch area, drawn as a dashed outline (reference only). */
  watchBoxes?: VesselBox[];
  tileUrl?: string;
  tileAttribution?: string;
  initialCenter?: LngLatLike;
}

export default function WorldMap({
  events,
  onSelect,
  vessels,
  showVessels,
  onVesselSelect,
  watchBoxes,
  tileUrl,
  tileAttribution,
  initialCenter,
}: Props) {
  const containerRef = useRef<HTMLDivElement>(null);
  const mapRef = useRef<MapLibreMap | null>(null);
  const popupRef = useRef<Popup | null>(null);

  const onSelectRef = useRef(onSelect);
  useEffect(() => {
    onSelectRef.current = onSelect;
  }, [onSelect]);

  const onVesselSelectRef = useRef(onVesselSelect);
  useEffect(() => {
    onVesselSelectRef.current = onVesselSelect;
  }, [onVesselSelect]);

  const featureCollection = useMemo<FeatureCollection<Point>>(() => {
    return {
      type: "FeatureCollection",
      features: events
        .filter((e) => typeof e.primaryGeo.lat === "number" && typeof e.primaryGeo.lng === "number")
        .map((e) => {
          const style = PRECISION_STYLE[e.primaryGeo.kind ?? "country"] ?? PRECISION_STYLE.uncertain;
          return {
            type: "Feature",
            geometry: { type: "Point", coordinates: [e.primaryGeo.lng!, e.primaryGeo.lat!] },
            properties: {
              id: e.id,
              title: e.title,
              level: e.significance.level,
              radius: style.radius,
              opacity: style.opacity,
              strokeOpacity: style.opacity < 0.4 ? 0.6 : 0,
            },
          };
        }),
    };
  }, [events]);

  const vesselFeatureCollection = useMemo<FeatureCollection<Point>>(() => {
    return {
      type: "FeatureCollection",
      features: (vessels ?? [])
        .filter((v) => typeof v.lat === "number" && typeof v.lng === "number")
        .map((v) => ({
          type: "Feature",
          geometry: { type: "Point", coordinates: [v.lng, v.lat] },
          properties: {
            mmsi: v.mmsi,
            name: v.name ?? "",
            sog: v.sog ?? "",
            cog: v.cog ?? "",
            navStatus: v.navStatus ?? "",
            observedAt: v.observedAt,
            naval: v.naval?.kind ?? "",
            navalReason: v.naval?.reason ?? "",
          },
        })),
    };
  }, [vessels]);

  const watchAreaFeatureCollection = useMemo(
    () => watchAreaCollection(watchBoxes ?? []),
    [watchBoxes],
  );

  const chokepointFeatureCollection = useMemo<FeatureCollection<Point>>(
    () => ({
      type: "FeatureCollection",
      features: CHOKEPOINTS.map((c) => ({
        type: "Feature",
        geometry: { type: "Point", coordinates: [c.lng, c.lat] },
        properties: { id: c.id, name: c.name, note: c.note },
      })),
    }),
    [],
  );

  // Create the map once per tile configuration.
  useEffect(() => {
    const container = containerRef.current;
    if (!container) return;

    const map = new MapLibreMap({
      container,
      style: tileUrl
        ? rasterStyle(tileUrl, tileAttribution)
        : STYLE_URLS.light,
      center: initialCenter ?? [20, 20],
      zoom: 1.6,
      minZoom: 1,
      maxZoom: 10,
      cooperativeGestures: true,
      attributionControl: false,
      trackResize: true,
    });
    mapRef.current = map;

    popupRef.current = new Popup({
      closeButton: false,
      closeOnClick: false,
      offset: 10,
      maxWidth: "280px",
    });

    map.addControl(
      new AttributionControl({
        compact: true,
        customAttribution: tileUrl ? undefined : OPENFREEMAP_ATTRIBUTION,
      }),
      "bottom-right",
    );
    map.addControl(new NavigationControl({ showCompass: false }), "top-right");

    const addLayers = () => {
      if (!map.getSource(WATCH_SOURCE)) {
        map.addSource(WATCH_SOURCE, { type: "geojson", data: watchAreaFeatureCollection });
      }
      if (!map.getLayer(WATCH_LAYER)) map.addLayer(buildWatchLayer());

      if (!map.getSource(CHOKE_SOURCE)) {
        map.addSource(CHOKE_SOURCE, { type: "geojson", data: chokepointFeatureCollection });
      }
      if (!map.getLayer(CHOKE_LAYER)) map.addLayer(buildChokeLayer());

      if (!map.getSource(EVENT_SOURCE)) {
        map.addSource(EVENT_SOURCE, { type: "geojson", data: featureCollection });
      }
      if (!map.getLayer(EVENT_LAYER)) map.addLayer(buildEventLayer());

      if (!map.getSource(VESSEL_SOURCE)) {
        map.addSource(VESSEL_SOURCE, { type: "geojson", data: vesselFeatureCollection });
      }
      if (!map.getLayer(VESSEL_LAYER)) map.addLayer(buildVesselLayer(showVessels ?? false));
    };

    if (tileUrl) addLayers();
    else map.once("style.load", addLayers);

    map.on("mouseenter", EVENT_LAYER, () => {
      map.getCanvas().style.cursor = "pointer";
    });
    map.on("mouseleave", EVENT_LAYER, () => {
      map.getCanvas().style.cursor = "";
      popupRef.current?.remove();
    });
    map.on("mousemove", EVENT_LAYER, (e) => {
      const feature = e.features?.[0];
      if (!feature || feature.geometry.type !== "Point") return;
      const coordinates = feature.geometry.coordinates as [number, number];
      const props = (feature.properties ?? {}) as Record<string, string>;
      const el = document.createElement("div");
      el.className = "orbis-map-popup";
      const title = document.createElement("div");
      title.className = "orbis-map-popup-title";
      title.textContent = String(props.title ?? "");
      const meta = document.createElement("div");
      meta.className = "orbis-map-popup-meta";
      meta.textContent = `${String(props.level ?? "")} · ${String(props.id ?? "")}`;
      el.append(title, meta);
      popupRef.current?.setLngLat(coordinates).setDOMContent(el).addTo(map);
    });
    map.on("click", EVENT_LAYER, (e) => {
      const id = String(e.features?.[0]?.properties?.id ?? "");
      const found = events.find((ev) => ev.id === id);
      if (found) onSelectRef.current(found);
    });

    map.on("mouseenter", VESSEL_LAYER, () => {
      map.getCanvas().style.cursor = "pointer";
    });
    map.on("mouseleave", VESSEL_LAYER, () => {
      map.getCanvas().style.cursor = "";
      popupRef.current?.remove();
    });
    map.on("mousemove", VESSEL_LAYER, (e) => {
      const feature = e.features?.[0];
      if (!feature || feature.geometry.type !== "Point") return;
      const coordinates = feature.geometry.coordinates as [number, number];
      const p = (feature.properties ?? {}) as Record<string, string>;
      // Age is derived here (an event handler), never baked into the memo, so
      // rendering stays pure.
      const observedMs = Date.parse(p.observedAt ?? "");
      const age = Number.isFinite(observedMs)
        ? Math.max(0, Math.round((Date.now() - observedMs) / 60_000))
        : null;
      const bits: string[] = [`MMSI ${String(p.mmsi ?? "")}`];
      if (p.sog) bits.push(`${p.sog} kn`);
      if (p.cog) bits.push(`${p.cog}°`);
      if (p.navStatus) bits.push(p.navStatus);
      if (age !== null) bits.push(age <= 1 ? "just now" : `${age} min old`);

      const el = document.createElement("div");
      el.className = "orbis-map-popup";
      const title = document.createElement("div");
      title.className = "orbis-map-popup-title";
      title.textContent = p.name ? p.name : "Unnamed vessel";
      const nodes: HTMLElement[] = [title];
      if (p.naval === "listed" || p.naval === "possible") {
        const badge = document.createElement("div");
        badge.className = "orbis-map-popup-meta";
        badge.textContent =
          (p.naval === "listed"
            ? "⚑ LISTED NAVAL HULL (your reference list) — "
            : "⚑ POSSIBLE NAVAL/GOVERNMENT VESSEL (unverified) — ") +
          String(p.navalReason ?? "");
        nodes.push(badge);
      }
      const meta = document.createElement("div");
      meta.className = "orbis-map-popup-meta";
      meta.textContent = bits.join(" · ");
      const warn = document.createElement("div");
      warn.className = "orbis-map-popup-meta";
      warn.textContent = "AIS is context only, not a navigational aid.";
      nodes.push(meta, warn);
      el.append(...nodes);
      popupRef.current?.setLngLat(coordinates).setDOMContent(el).addTo(map);
    });
    map.on("click", VESSEL_LAYER, (e) => {
      const mmsi = String(e.features?.[0]?.properties?.mmsi ?? "");
      if (mmsi) onVesselSelectRef.current?.(mmsi);
    });

    map.on("mouseenter", CHOKE_LAYER, () => {
      map.getCanvas().style.cursor = "pointer";
    });
    map.on("mouseleave", CHOKE_LAYER, () => {
      map.getCanvas().style.cursor = "";
      popupRef.current?.remove();
    });
    map.on("mousemove", CHOKE_LAYER, (e) => {
      const feature = e.features?.[0];
      if (!feature || feature.geometry.type !== "Point") return;
      const coordinates = feature.geometry.coordinates as [number, number];
      const p = (feature.properties ?? {}) as Record<string, string>;
      const el = document.createElement("div");
      el.className = "orbis-map-popup";
      const title = document.createElement("div");
      title.className = "orbis-map-popup-title";
      title.textContent = String(p.name ?? "");
      const meta = document.createElement("div");
      meta.className = "orbis-map-popup-meta";
      meta.textContent = String(p.note ?? "");
      const warn = document.createElement("div");
      warn.className = "orbis-map-popup-meta";
      warn.textContent = "Static reference mark — not navigational data.";
      el.append(title, meta, warn);
      popupRef.current?.setLngLat(coordinates).setDOMContent(el).addTo(map);
    });

    return () => {
      popupRef.current?.remove();
      map.remove();
      mapRef.current = null;
    };
    // Recreate only when the tile configuration changes. Data updates are
    // pushed into the existing sources by the setData effects below.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [tileUrl, tileAttribution, initialCenter]);

  // Follow the light/dark theme when a vector style is used. With a raster
  // tile provider there is nothing to restyle.
  useEffect(() => {
    if (tileUrl) return;
    const root = document.documentElement;
    const applyTheme = () => {
      const map = mapRef.current;
      if (!map) return;
      const mode = root.dataset.theme === "dark" ? "dark" : "light";
      map.setStyle(STYLE_URLS[mode]);
      map.once("style.load", () => {
        if (!map.getSource(WATCH_SOURCE)) {
          map.addSource(WATCH_SOURCE, { type: "geojson", data: watchAreaFeatureCollection });
        }
        if (!map.getLayer(WATCH_LAYER)) map.addLayer(buildWatchLayer());
        if (!map.getSource(CHOKE_SOURCE)) {
          map.addSource(CHOKE_SOURCE, { type: "geojson", data: chokepointFeatureCollection });
        }
        if (!map.getLayer(CHOKE_LAYER)) map.addLayer(buildChokeLayer());
        if (!map.getSource(EVENT_SOURCE)) {
          map.addSource(EVENT_SOURCE, { type: "geojson", data: featureCollection });
        }
        if (!map.getLayer(EVENT_LAYER)) map.addLayer(buildEventLayer());
        if (!map.getSource(VESSEL_SOURCE)) {
          map.addSource(VESSEL_SOURCE, { type: "geojson", data: vesselFeatureCollection });
        }
        if (!map.getLayer(VESSEL_LAYER)) map.addLayer(buildVesselLayer(showVessels ?? false));
      });
    };
    applyTheme();
    const observer = new MutationObserver(applyTheme);
    observer.observe(root, { attributes: true, attributeFilter: ["data-theme"] });
    return () => observer.disconnect();
  }, [
    tileUrl,
    featureCollection,
    vesselFeatureCollection,
    watchAreaFeatureCollection,
    chokepointFeatureCollection,
    showVessels,
  ]);

  // Push refreshed data into the existing source without rebuilding the map.
  useEffect(() => {
    const source = mapRef.current?.getSource(EVENT_SOURCE) as GeoJSONSource | undefined;
    source?.setData(featureCollection);
  }, [featureCollection]);

  useEffect(() => {
    const source = mapRef.current?.getSource(VESSEL_SOURCE) as GeoJSONSource | undefined;
    source?.setData(vesselFeatureCollection);
  }, [vesselFeatureCollection]);

  useEffect(() => {
    const source = mapRef.current?.getSource(WATCH_SOURCE) as GeoJSONSource | undefined;
    source?.setData(watchAreaFeatureCollection);
  }, [watchAreaFeatureCollection]);

  // Show/hide the vessel layer without dropping the collected positions.
  useEffect(() => {
    const layer = mapRef.current?.getLayer(VESSEL_LAYER);
    if (!layer) return;
    mapRef.current?.setLayoutProperty(
      VESSEL_LAYER,
      "visibility",
      showVessels ? "visible" : "none",
    );
  }, [showVessels]);

  return (
    <div className="relative">
      <div
        ref={containerRef}
        className="h-[420px] w-full rounded-lg border border-line md:h-[560px]"
      />
      <p className="mt-1.5 text-[11px] text-muted">
        Vector basemap by OpenFreeMap, free and keyless. Hold Ctrl (or pinch) to zoom so the page
        keeps scrolling normally; ± controls zoom too. Only geolocated events are plotted, and
        low-precision events are drawn as areas. The dashed outline is the AIS watch area and the
        amber marks are major straits/canals — static reference geography, not navigational data.
        Violet/orange vessel dots carry naval badges: heuristics on public AIS (or your own MMSI
        list), never proof — military vessels often switch AIS off entirely, so absence from this
        layer means nothing.
      </p>
    </div>
  );
}
